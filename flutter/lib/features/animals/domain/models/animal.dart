class Animal {
  final String id;
  final String name;
  final String type;
  final String breed;
  final String age;
  final String imageUrl;
  final double healthScore;
  final String lastChecked;

  Animal({
    required this.id,
    required this.name,
    required this.type,
    required this.breed,
    required this.age,
    required this.imageUrl,
    required this.healthScore,
    required this.lastChecked,
  });
}
